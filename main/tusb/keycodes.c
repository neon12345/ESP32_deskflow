// Lookup table: UTF-32 char -> HID usage code (German QWERTZ)
// Deskflow sends Unicode char values. Map to the HID key that produces that char on DE layout.
// Modifiers (Shift, AltGr) are sent separately via the mask -- EXCEPT this table has no way to
// signal "this char needs AltGr" back to the caller (barrier_key_to_hid only returns one usage
// byte). Characters that only exist behind AltGr on German layout (@ [ ] { } | ~ \) are therefore
// left unmapped (0x00) rather than pointing at a plain key that produces the wrong character.
