    //  '  '   !   "   #   $   %   &   '   (   )   *   +   ,   -   .   /
    // '#' -> Non-US "#~" key (0x32), not shift+3 (which is section-sign section-sign on DE)
    // '\'' -> no clean single key on DE (needs the acute dead-key), left unmapped
    // '*' -> the +/* key (0x30), NOT the same key as '('
    // '+' -> the +/* key (0x30), NOT the same key as '='
