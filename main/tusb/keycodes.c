// Sparse lookup for Unicode characters above 0xFF
static const struct { uint16_t ch; uint8_t hid; } HIGH_CHARS[] = {
    { 0x20AC, 0x08 },  // € -> e (HID_KEY_E)
    { 0x0302, 0x35 },
    { 0x0301, 0x2E },
    { 0x0300, 0x2E },
};
#define HIGH_CHARS_COUNT (sizeof(HIGH_CHARS) / sizeof(HIGH_CHARS[0]))

static const uint8_t *s_table   = TABLE_US;

void keycodes_set_layout(uint8_t layout)
{
    if (layout >= KEYBOARD_LAYOUT_COUNT) return;
    switch (layout) {
        case KEYBOARD_LAYOUT_US:
            s_table   = TABLE_US;
            break;
        case KEYBOARD_LAYOUT_DE:
            s_table   = TABLE_DE;
            break;
    }
}

uint8_t barrier_key_to_hid(uint16_t barrier_key)
{
    uint8_t hid;
    if (barrier_key == BARRIER_KEY_LEFT_TAB) {
        return HID_KEY_TAB;
    } else if (barrier_key < 0x100) {
        hid = s_table[barrier_key];
    } else if (barrier_key >= BARRIER_EXT_BASE && barrier_key <= BARRIER_EXT_BASE + 255) {
        hid = EXT_TAB[barrier_key - BARRIER_EXT_BASE];
    } else {
        // Check high-range Unicode characters
        hid = HID_KEY_NONE;
        for (uint8_t i = 0; i < HIGH_CHARS_COUNT; i++) {
            if (HIGH_CHARS[i].ch == barrier_key) {
                hid = HIGH_CHARS[i].hid;
                break;
            }
        }
    }
    // here adds needless per-keystroke overhead on a KVM/keyboard-forwarding path.
    ESP_LOGD("keycodes", "key 0x%04x -> HID 0x%02x [%s]", barrier_key, hid, hid == 0 ? "UNMAPPED" : "OK");
    return hid;
}

uint8_t mask_to_tusb_modifier(uint16_t df_mask)
{
    uint8_t modifier = 0;

    // Deskflow uses LOGICAL modifiers, not left/right. Map to left-side HID keys.
    // AltGr -> Right Ctrl (physically Right Ctrl on ALL PC keyboards,
    // the OS interprets Right Ctrl as AltGr for layout purposes)
    // Meta -> Right Alt (X11 convention)
    if (df_mask & DF_MASK_SHIFT)      modifier |= HID_MOD_LEFT_SHIFT;
    if (df_mask & DF_MASK_CONTROL)    modifier |= HID_MOD_LEFT_CTRL;
    if (df_mask & DF_MASK_ALT)        modifier |= HID_MOD_LEFT_ALT;
    if (df_mask & DF_MASK_META)       modifier |= HID_MOD_RIGHT_ALT;
    if (df_mask & DF_MASK_SUPER)      modifier |= HID_MOD_LEFT_GUI;
    if (df_mask & DF_MASK_ALTGR)      modifier |= HID_MOD_RIGHT_ALT;
    // Level5Lock and CapsLock have no HID modifier bit

    ESP_LOGD("keycodes", "mask 0x%04x -> HID mod 0x%02x", df_mask, modifier);
    return modifier;
}
